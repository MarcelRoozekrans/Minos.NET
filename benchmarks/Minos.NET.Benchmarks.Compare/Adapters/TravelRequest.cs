namespace Minos.Benchmarks.Compare.Adapters;

/// <summary>The workload's <c>intent</c> options, in the order the workload sends them.</summary>
public enum TravelIntent
{
    /// <summary><c>look_up_booking</c>.</summary>
    [Criteria("Wants to see or look up an existing booking")]
    LookUpBooking,

    /// <summary><c>change_booking</c>.</summary>
    [Criteria("Wants to change dates, names, seats or luggage on a booking")]
    ChangeBooking,

    /// <summary><c>dispute_charge</c>.</summary>
    [Criteria("Disputes a charge or asks for money back")]
    DisputeCharge,

    /// <summary><c>other</c>.</summary>
    [Criteria("Anything else")]
    Other,
}

/// <summary>The workload's question set, generated by Minos.NET, with the keys <c>intent</c> and <c>travels_within24_hours</c>.</summary>
[Questions]
public partial record TravelRequest
{
    /// <summary>Gets the <c>intent</c> answer.</summary>
    [Choice(Workload.IntentInstructions)]
    public partial Choice<TravelIntent> Intent { get; }

    /// <summary>Gets the <c>travels_within24_hours</c> answer.</summary>
    [Noul(Workload.TravelsSoonInstructions)]
    public partial Noul TravelsWithin24Hours { get; }
}
